<?php

declare(strict_types=1);

namespace Shirakaba\Database;

use Closure;
use Shirakaba\Database\Error\DatabaseError;
use Shirakaba\Database\Error\TransientFailure;

/**
 * Read and write access, including transactions.
 */
final class Writer extends Reader
{
    /**
     * @param array<string|int, scalar|\DateTimeImmutable|\Shirakaba\Time\LocalDate|\BackedEnum|null> $parameters
     * @return int affected rows
     * @throws DatabaseError when the statement fails
     * @phpstan-impure io.db
     */
    public function execute(string $sql, array $parameters = []): int
    {
        return $this->connection->run($sql, $parameters, $this->timeout)->rowCount();
    }

    /**
     * The key generated by the last INSERT. Prefer RETURNING where the dialect supports it.
     *
     * @phpstan-impure io.db
     */
    public function lastInsertId(): string
    {
        return (string) $this->connection->pdo->lastInsertId();
    }

    /**
     * Runs $callback after the outermost transaction commits, or at once outside one; a
     * rollback discards it.
     *
     * @param Closure(): void $callback
     */
    public function afterCommit(Closure $callback): void
    {
        $this->connection->afterCommit($callback);
    }

    /**
     * Runs $work in a transaction: committed when it returns, rolled back when it throws.
     * Inside another transaction it runs in a savepoint, so an inner failure rolls back
     * only the inner work.
     *
     * An outermost transaction that fails with a TransientFailure (deadlock, serialisation
     * failure) is run again up to $retries times; $work must then be safe to repeat.
     * Whatever $work throws is rethrown; failing statements and commits throw DatabaseError.
     *
     * @template T
     * @param Closure(Writer): T $work
     * @param int<0, max> $retries
     * @return T
     * @phpstan-impure io.db
     */
    public function transaction(Closure $work, int $retries = 0): mixed
    {
        $outermost = !$this->connection->inTransaction();
        for ($attempt = 0; ; $attempt++) {
            try {
                return $this->connection->transaction($work, $this);
            } catch (TransientFailure $e) {
                if (!$outermost || $attempt >= $retries) {
                    throw $e;
                }
            }
        }
    }
}

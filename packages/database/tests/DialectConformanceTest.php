<?php

declare(strict_types=1);

namespace Shirakaba\Database\Tests;

use DateTimeImmutable;
use LogicException;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Shirakaba\Database\Connection;
use Shirakaba\Database\Database;
use Shirakaba\Database\Dialect\Instants;
use Shirakaba\Database\Dialect\MySql;
use Shirakaba\Database\Dialect\PostgreSql;
use Shirakaba\Database\Dialect\Quoting;
use Shirakaba\Database\Dialect\Sqlite;
use Shirakaba\Database\Error\ForeignKeyViolation;
use Shirakaba\Database\Error\NotNullViolation;
use Shirakaba\Database\Error\UniqueViolation;
use Shirakaba\Database\Reader;
use Shirakaba\Database\Testing\TestDatabases;
use Shirakaba\Database\Writer;
use Shirakaba\Time\LocalDate;

/**
 * Runs on SQLite always, and on MySQL and PostgreSQL when their DSNs are configured
 * (TestDatabases).
 */
#[CoversClass(Connection::class)]
#[CoversClass(MySql::class)]
#[CoversClass(PostgreSql::class)]
#[CoversClass(Sqlite::class)]
#[CoversClass(Quoting::class)]
#[CoversClass(Instants::class)]
#[CoversClass(Reader::class)]
#[CoversClass(Writer::class)]
final class DialectConformanceTest extends TestCase
{
    /**
     * @return array<string, array{Database}>
     */
    public static function databases(): array
    {
        return TestDatabases::available();
    }

    /**
     * Drivers return integers as int or numeric strings depending on the column type.
     */
    private static function int(mixed $value): int
    {
        self::assertTrue(is_int($value) || is_bool($value) || (is_string($value) && is_numeric($value)), 'Expected an integer, got ' . var_export($value, true));

        return (int) $value;
    }

    private static function prepare(Database $database): Writer
    {
        $db = $database->connect()->writer();
        $q = $db->dialect()->quoteIdentifier(...);
        $db->execute('DROP TABLE IF EXISTS shirakaba_children');
        $db->execute('DROP TABLE IF EXISTS shirakaba_parents');
        $id = match ($db->dialect()->name()) {
            'mysql' => 'BIGINT AUTO_INCREMENT PRIMARY KEY',
            'pgsql' => 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
            default => 'INTEGER PRIMARY KEY AUTOINCREMENT',
        };
        $instant = match ($db->dialect()->name()) {
            'mysql' => 'DATETIME(6)',
            'pgsql' => 'TIMESTAMPTZ(6)',
            default => 'TEXT',
        };
        $db->execute(sprintf('CREATE TABLE shirakaba_parents (id %s, %s VARCHAR(50) NOT NULL UNIQUE, %s %s NULL, %s DATE NULL, %s BOOLEAN NOT NULL DEFAULT FALSE)', $id, $q('name'), $q('at'), $instant, $q('day'), $q('flag')));
        $db->execute(sprintf('CREATE TABLE shirakaba_children (id %s, parent_id BIGINT NOT NULL, FOREIGN KEY (parent_id) REFERENCES shirakaba_parents (id))', $id));

        return $db;
    }

    #[DataProvider('databases')]
    public function testBindsTypesAndReadsInstantsBackInUtc(Database $database): void
    {
        $db = self::prepare($database);
        $at = new DateTimeImmutable('2026-11-11T09:30:00.123456+09:00');
        $db->execute('INSERT INTO shirakaba_parents (name, at, day, flag) VALUES (?, ?, ?, ?)', ['a', $at, LocalDate::of(2026, 11, 11), true]);
        $row = $db->fetchOne('SELECT at, day, flag FROM shirakaba_parents WHERE name = ? AND flag = ?', ['a', true]);

        self::assertNotNull($row);
        $at = $row['at'] ?? null;
        self::assertIsString($at);
        $read = $db->dialect()->parseInstant($at);
        self::assertNotNull($read);
        self::assertSame('2026-11-11T00:30:00.123456+00:00', $read->format('Y-m-d\TH:i:s.uP'));
        self::assertSame('2026-11-11', $row['day'] ?? null);
        self::assertSame(1, self::int($row['flag'] ?? null));
        self::assertSame(1, self::int($db->fetchValue('SELECT COUNT(*) FROM shirakaba_parents WHERE at < ?', [new DateTimeImmutable('2026-11-11T09:30:01+09:00')])));
        self::assertSame(0, self::int($db->fetchValue('SELECT COUNT(*) FROM shirakaba_parents WHERE at < ?', [new DateTimeImmutable('2026-11-11T00:30:00Z')])));
    }

    /**
     * PostgreSQL leaves out trailing zeros of the fraction, so microseconds such as 123000
     * come back in a string as long as MySQL's DATETIME(6).
     */
    #[DataProvider('databases')]
    public function testReadsInstantsWhoseFractionEndsInZeros(Database $database): void
    {
        $db = self::prepare($database);
        foreach (['123000', '120000', '100000', '000000'] as $index => $micro) {
            $db->execute('INSERT INTO shirakaba_parents (name, at) VALUES (?, ?)', ['m' . $index, new DateTimeImmutable('2026-11-11T11:20:33.' . $micro . 'Z')]);
            $at = $db->fetchValue('SELECT at FROM shirakaba_parents WHERE name = ?', ['m' . $index]);
            self::assertIsString($at);
            self::assertSame('2026-11-11T11:20:33.' . $micro . '+00:00', $db->dialect()->parseInstant($at)?->format('Y-m-d\TH:i:s.uP'), $at);
        }
    }

    #[DataProvider('databases')]
    public function testClassifiesConstraintViolations(Database $database): void
    {
        $db = self::prepare($database);
        $db->execute('INSERT INTO shirakaba_parents (name) VALUES (?)', ['a']);

        try {
            $db->execute('INSERT INTO shirakaba_parents (name) VALUES (?)', ['a']);
            self::fail('Expected a unique violation.');
        } catch (UniqueViolation) {
        }
        try {
            $db->execute('INSERT INTO shirakaba_children (parent_id) VALUES (?)', [999]);
            self::fail('Expected a foreign key violation.');
        } catch (ForeignKeyViolation) {
        }
        $this->expectException(NotNullViolation::class);
        $db->execute('INSERT INTO shirakaba_parents (name) VALUES (?)', [null]);
    }

    #[DataProvider('databases')]
    public function testNestedTransactionsUseSavepoints(Database $database): void
    {
        $db = self::prepare($database);
        $db->transaction(static function (Writer $db): void {
            $db->execute('INSERT INTO shirakaba_parents (name) VALUES (?)', ['outer']);
            try {
                $db->transaction(static function (Writer $db): void {
                    $db->execute('INSERT INTO shirakaba_parents (name) VALUES (?)', ['inner']);

                    throw new LogicException('inner fails');
                });
            } catch (LogicException) {
            }
            $db->execute('INSERT INTO shirakaba_parents (name) VALUES (?)', ['after']);
        });

        self::assertSame(['after', 'outer'], array_column($db->fetchAll('SELECT name FROM shirakaba_parents ORDER BY name'), 'name'));
    }

    #[DataProvider('databases')]
    public function testAfterCommitCallbacksFollowTheOutermostCommit(Database $database): void
    {
        $db = $database->connect()->writer();
        $log = new \ArrayObject();
        $db->afterCommit(static fn () => $log->append('immediately'));
        $db->transaction(static function (Writer $db) use ($log): void {
            $db->afterCommit(static fn () => $log->append('outer'));
            try {
                $db->transaction(static function (Writer $db) use ($log): void {
                    $db->afterCommit(static fn () => $log->append('rolled back'));

                    throw new LogicException('inner fails');
                });
            } catch (LogicException) {
            }
            $db->transaction(static fn (Writer $db) => $db->afterCommit(static fn () => $log->append('inner')));
            $log->append('before commit');
        });
        try {
            $db->transaction(static function (Writer $db) use ($log): void {
                $db->afterCommit(static fn () => $log->append('never'));

                throw new LogicException('outer fails');
            });
        } catch (LogicException) {
        }

        self::assertSame(['immediately', 'before commit', 'outer', 'inner'], $log->getArrayCopy());
    }

    #[DataProvider('databases')]
    public function testUpsertAndLimit(Database $database): void
    {
        $db = self::prepare($database);
        $dialect = $db->dialect();
        $name = $dialect->quoteIdentifier('name');
        $flag = $dialect->quoteIdentifier('flag');
        $sql = sprintf('INSERT INTO shirakaba_parents (%s, %s) VALUES (?, ?) %s', $name, $flag, $dialect->upsert('shirakaba_parents', [$name], [$flag => 'excluded.' . $flag]));
        $db->execute($sql, ['a', false]);
        $db->execute($sql, ['a', true]);
        $db->execute('INSERT INTO shirakaba_parents (name) VALUES (?), (?), (?)', ['b', 'c', 'd']);

        self::assertSame(1, self::int($db->fetchValue('SELECT flag FROM shirakaba_parents WHERE name = ?', ['a'])));
        self::assertSame(['b', 'c'], array_column($db->fetchAll('SELECT name FROM shirakaba_parents ORDER BY name ' . $dialect->limit(2, 1)), 'name'));
        self::assertSame(['c', 'd'], array_column($db->fetchAll('SELECT name FROM shirakaba_parents ORDER BY name ' . $dialect->limit(null, 2)), 'name'));
        self::assertSame(['a', 'b', 'c', 'd'], array_column(iterator_to_array($db->iterate('SELECT name FROM shirakaba_parents ORDER BY name'), false), 'name'));
    }

    #[DataProvider('databases')]
    public function testSessionIsUtc(Database $database): void
    {
        $db = $database->connect()->reader();
        $now = match ($db->dialect()->name()) {
            'mysql' => 'SELECT @@session.time_zone',
            'pgsql' => 'SHOW TIME ZONE',
            default => null,
        };
        if ($now === null) {
            self::assertSame(1, self::int($db->fetchValue('PRAGMA foreign_keys')));

            return;
        }
        self::assertContains($db->fetchValue($now), ['+00:00', 'UTC']);
    }

    public function testQuotesIdentifiers(): void
    {
        self::assertSame('`a``b`.`c`', new MySql()->quoteIdentifier('a`b.c'));
        self::assertSame('"a""b".*', new PostgreSql()->quoteIdentifier('a"b.*'));
        self::assertSame('"users"."id"', new Sqlite()->quoteIdentifier('users.id'));
    }

    public function testParsesDriverInstants(): void
    {
        self::assertSame('2026-11-11T00:30:00.500000+00:00', Instants::parse('2026-11-11 09:30:00.5+09')?->format('Y-m-d\TH:i:s.uP'));
        self::assertSame('2026-11-11T00:30:00.000000+00:00', Instants::parse('2026-11-11 00:30:00')?->format('Y-m-d\TH:i:s.uP'));
        // As long as MySQL's DATETIME(6), but PostgreSQL's with trailing zeros left out.
        self::assertSame('2026-11-11T11:20:33.123000+00:00', Instants::parse('2026-11-11 11:20:33.123+00')?->format('Y-m-d\TH:i:s.uP'));
        self::assertSame('2026-11-11T11:20:33.123456+00:00', Instants::parse('2026-11-11 11:20:33.123456')?->format('Y-m-d\TH:i:s.uP'));
        self::assertSame('2026-11-11T11:20:33.123456+00:00', Instants::parse('2026-11-11T11:20:33.123456Z')?->format('Y-m-d\TH:i:s.uP'));
        self::assertNull(Instants::parse('2026-02-30 00:00:00'));
        self::assertNull(Instants::parse('yesterday'));
    }
}

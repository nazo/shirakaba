<?php

declare(strict_types=1);

namespace Shirakaba\Query\Tests;

use DateTimeImmutable;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Shirakaba\Database\Database;
use Shirakaba\Database\Error\UniqueViolation;
use Shirakaba\Database\Testing\TestDatabases;
use Shirakaba\Database\Writer;
use Shirakaba\Query\Delete;
use Shirakaba\Query\Insert;
use Shirakaba\Query\RowMapper;
use Shirakaba\Query\Select;
use Shirakaba\Query\Sql;
use Shirakaba\Query\Tests\Fixtures\Status;
use Shirakaba\Query\Tests\Fixtures\TaskRow;
use Shirakaba\Query\Update;
use Shirakaba\Time\LocalDate;

/**
 * The same builder calls give the same results on every available database.
 */
#[CoversClass(Select::class)]
#[CoversClass(Insert::class)]
#[CoversClass(Update::class)]
#[CoversClass(Delete::class)]
#[CoversClass(RowMapper::class)]
final class DatabaseConformanceTest extends TestCase
{
    /**
     * @return array<string, array{Database}>
     */
    public static function databases(): array
    {
        return TestDatabases::available();
    }

    private static function tasks(Database $database): Writer
    {
        $db = $database->connect()->writer();
        $db->execute('DROP TABLE IF EXISTS query_tasks');
        [$id, $instant] = match ($db->dialect()->name()) {
            'mysql' => ['BIGINT AUTO_INCREMENT PRIMARY KEY', 'DATETIME(6)'],
            'pgsql' => ['BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'TIMESTAMPTZ(6)'],
            default => ['INTEGER PRIMARY KEY AUTOINCREMENT', 'TEXT'],
        };
        $db->execute(sprintf(
            'CREATE TABLE query_tasks (id %s, title VARCHAR(100) NOT NULL UNIQUE, done BOOLEAN NOT NULL, status VARCHAR(10) NOT NULL, created_at %s NOT NULL, due_on DATE NULL, weight DECIMAL(5, 2) NOT NULL DEFAULT 1)',
            $id,
            $instant,
        ));

        return $db;
    }

    #[DataProvider('databases')]
    public function testInsertsSelectsAndMapsRows(Database $database): void
    {
        $db = self::tasks($database);
        $created = new DateTimeImmutable('2026-11-11T09:00:00.5+09:00');
        $first = Insert::into('query_tasks')
            ->values(['title' => 'Write', 'done' => false, 'status' => Status::Open, 'created_at' => $created, 'due_on' => LocalDate::of(2026, 12, 1), 'weight' => 2.5])
            ->executeAndGetId($db);
        Insert::into('query_tasks')->rows([
            ['title' => 'Test', 'done' => true, 'status' => Status::Done, 'created_at' => $created, 'due_on' => null, 'weight' => 1],
            ['title' => 'Ship', 'done' => false, 'status' => Status::Open, 'created_at' => $created->modify('+1 day'), 'due_on' => null, 'weight' => 1],
        ])->execute($db);

        $open = Select::from('query_tasks')->where('done', '=', false)->orderBy('id')->fetchInto(TaskRow::class, $db);

        self::assertSame(1, $first);
        self::assertSame(['Write', 'Ship'], array_map(static fn (TaskRow $task): string => $task->title, $open));
        $write = $open[0] ?? null;
        self::assertNotNull($write);
        self::assertSame(Status::Open, $write->status);
        self::assertFalse($write->done);
        self::assertSame(2.5, $write->weight);
        self::assertSame('2026-12-01', (string) $write->dueOn);
        self::assertSame('2026-11-11T00:00:00.500000+00:00', $write->createdAt->format('Y-m-d\TH:i:s.uP'));

        self::assertSame(3, Select::from('query_tasks')->count($db));
        self::assertSame(2, Select::from('query_tasks')->where('created_at', '<', new DateTimeImmutable('2026-11-11T12:00:00+09:00'))->count($db));
        self::assertTrue(Select::from('query_tasks')->where('status', '=', Status::Done)->exists($db));
        self::assertFalse(Select::from('query_tasks')->whereIn('id', [])->exists($db));
        self::assertSame(['Ship'], array_column(Select::from('query_tasks')->columns('title')->orderBy('id')->after(['id' => 2])->fetchAll($db), 'title'));
    }

    #[DataProvider('databases')]
    public function testUpdatesDeletesAndUpserts(Database $database): void
    {
        $db = self::tasks($database);
        $row = ['title' => 'Write', 'done' => false, 'status' => 'open', 'created_at' => new DateTimeImmutable('2026-11-11T00:00:00Z')];
        Insert::into('query_tasks')->values($row)->execute($db);

        Insert::into('query_tasks')->values([...$row, 'done' => true])->onConflict(['title'], ['done'])->execute($db);
        self::assertSame(1, Select::from('query_tasks')->count($db));
        self::assertTrue(Select::from('query_tasks')->fetchOneInto(TaskRow::class, $db)?->done);

        Insert::into('query_tasks')->values([...$row, 'status' => 'done'])->onConflict(['title'])->execute($db);
        self::assertSame('open', Select::from('query_tasks')->columns('status')->fetchValue($db));

        // An expression on the stored and the inserted row: weight 1 + 3 + 2.
        Insert::into('query_tasks')->values([...$row, 'weight' => 3])->onConflict(['title'], ['weight' => Sql::raw('query_tasks.weight + excluded.weight + ?', [2])])->execute($db);
        $added = Select::from('query_tasks')->columns('weight')->fetchValue($db);
        self::assertTrue(is_numeric($added));
        self::assertSame(6.0, (float) $added);
        Update::table('query_tasks')->set(['weight' => 1])->where('title', '=', 'Write')->execute($db);

        self::assertSame(1, Update::table('query_tasks')->set(['weight' => Sql::raw('weight + 1')])->where('title', '=', 'Write')->execute($db));
        $weight = Select::from('query_tasks')->columns('weight')->fetchValue($db);
        self::assertTrue(is_numeric($weight));
        self::assertSame(2.0, (float) $weight);

        try {
            Insert::into('query_tasks')->values($row)->execute($db);
            self::fail('Expected a unique violation.');
        } catch (UniqueViolation) {
        }

        self::assertSame(1, Delete::from('query_tasks')->where('title', '=', 'Write')->execute($db));
        self::assertFalse(Select::from('query_tasks')->exists($db));
    }
}

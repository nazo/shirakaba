<?php

declare(strict_types=1);

namespace Shirakaba\Orm;

use BackedEnum;
use DateTimeImmutable;
use ReflectionEnum;
use Shirakaba\Database\Error\DatabaseError;
use Shirakaba\Database\Reader;
use Shirakaba\Orm\Mapping\EntityMap;
use Shirakaba\Orm\Mapping\Field;
use Shirakaba\Time\LocalDate;

/**
 * Writes a migration for the difference between entity mappings and the live schema
 *: missing tables (with their foreign keys and many-to-many join tables) and
 * missing columns. It never drops or changes anything; review the generated class, add
 * indexes, and lint it before running it.
 *
 *     $source = SchemaDiff::migration([Post::class, Author::class], $reader, 'AddPosts', 'App\Migrations');
 */
final readonly class SchemaDiff
{
    /**
     * @param list<class-string> $entities
     * @return string|null PHP source of a migration class, or null when nothing is missing
     * @throws DatabaseError
     */
    public static function migration(array $entities, Reader $db, string $className, string $namespace = ''): ?string
    {
        $maps = [];
        foreach ($entities as $entity) {
            $maps[$entity] = EntityMap::of($entity);
        }
        $creates = [];
        $alters = [];
        $joins = [];
        foreach (self::ordered($maps) as $map) {
            $live = SchemaCheck::columns($map->table, $db);
            if ($live === []) {
                $creates[] = self::create($map, $maps);
            } else {
                $lines = [];
                foreach (self::flatten($map->fields, false) as [$field, $nullable]) {
                    if (!isset($live[$field->column])) {
                        $lines[] = self::column($field, $nullable);
                    }
                }
                if ($lines !== []) {
                    $alters[] = self::block('alter', $map->table, $lines);
                }
            }
            foreach ($map->relations as $relation) {
                $through = $relation->through;
                if ($relation->kind === 'manyToMany' && $through !== null && !isset($joins[$through]) && SchemaCheck::columns($through, $db) === []) {
                    $related = $maps[$relation->entity] ?? EntityMap::of($relation->entity);
                    $local = $relation->localKey ?? 'id';
                    $joins[$through] = self::block('create', $through, [
                        sprintf('$table->bigInteger(%s);', var_export($local, true)),
                        sprintf('$table->bigInteger(%s);', var_export($relation->foreignKey, true)),
                        ...($relation->orderBy === null ? [] : [sprintf('$table->integer(%s)->default(0);', var_export($relation->orderBy, true))]),
                        sprintf('$table->primary([%s, %s]);', var_export($local, true), var_export($relation->foreignKey, true)),
                        sprintf(
                            '$table->foreign(%s)->references(%s, %s)->onDelete(\'cascade\');',
                            var_export($local, true),
                            var_export($map->table, true),
                            var_export(($map->ids()[0] ?? null)->column ?? 'id', true),
                        ),
                        sprintf(
                            '$table->foreign(%s)->references(%s, %s)->onDelete(\'cascade\');',
                            var_export($relation->foreignKey, true),
                            var_export($related->table, true),
                            var_export(($related->ids()[0] ?? null)->column ?? 'id', true),
                        ),
                    ]);
                }
            }
        }
        $blocks = [...$creates, ...array_values($joins), ...$alters];
        if ($blocks === []) {
            return null;
        }

        return sprintf(
            "<?php\n\ndeclare(strict_types=1);\n%s\nuse Shirakaba\\Migrations\\Blueprint;\nuse Shirakaba\\Migrations\\Migration;\nuse Shirakaba\\Migrations\\Schema;\n\n/**\n * Generated by SchemaDiff; review it, add indexes, and lint it before running it.\n */\nfinal readonly class %s implements Migration\n{\n    public function up(Schema \$schema): void\n    {\n%s\n    }\n}\n",
            $namespace === '' ? '' : "\nnamespace {$namespace};\n",
            $className,
            implode("\n", $blocks),
        );
    }

    /**
     * Tables in an order where referenced tables come first.
     *
     * @param array<class-string, EntityMap<object>> $maps
     * @return list<EntityMap<object>>
     */
    private static function ordered(array $maps): array
    {
        $ordered = [];
        $seen = [];
        $visit = static function (string $class) use (&$visit, &$ordered, &$seen, $maps): void {
            if (isset($seen[$class]) || !isset($maps[$class])) {
                return;
            }
            $seen[$class] = true;
            foreach ($maps[$class]->relations as $relation) {
                if ($relation->kind === 'belongsTo' && $relation->entity !== $class) {
                    $visit($relation->entity);
                }
            }
            $ordered[] = $maps[$class];
        };
        foreach (array_keys($maps) as $class) {
            $visit($class);
        }

        return $ordered;
    }

    /**
     * @param EntityMap<object> $map
     * @param array<class-string, EntityMap<object>> $maps
     */
    private static function create(EntityMap $map, array $maps): string
    {
        $ids = $map->ids();
        $lines = [];
        $generatedId = count($ids) === 1 && $ids[0]->generated && in_array($ids[0]->kind === 'wrapper' ? $ids[0]->innerType : $ids[0]->type, ['int'], true);
        $fields = self::flatten($map->fields, false);
        // Key columns first, whatever the constructor order (generated keys come last there).
        usort($fields, static fn (array $a, array $b): int => (int) $b[0]->id <=> (int) $a[0]->id);
        foreach ($fields as [$field, $nullable]) {
            if ($generatedId && $field->id) {
                $lines[] = $field->column === 'id' ? '$table->id();' : sprintf('$table->id(%s);', var_export($field->column, true));
                continue;
            }
            $lines[] = self::column($field, $nullable);
        }
        if (!$generatedId) {
            $lines[] = sprintf('$table->primary([%s]);', implode(', ', array_map(static fn (Field $id): string => var_export($id->column, true), $ids)));
        }
        foreach ($map->relations as $relation) {
            if ($relation->kind !== 'belongsTo') {
                continue;
            }
            $related = $maps[$relation->entity] ?? EntityMap::of($relation->entity);
            $lines[] = sprintf(
                '$table->foreign(%s)->references(%s, %s);',
                var_export($map->field($relation->foreignKey)->column, true),
                var_export($related->table, true),
                var_export(($related->ids()[0] ?? null)->column ?? 'id', true),
            );
        }

        return self::block('create', $map->table, $lines);
    }

    /**
     * @param list<Field> $fields
     * @return list<array{Field, bool}> stored fields with their effective nullability
     */
    private static function flatten(array $fields, bool $parentNullable): array
    {
        $flat = [];
        foreach ($fields as $field) {
            if ($field->kind === 'embedded') {
                foreach (self::flatten($field->children, $parentNullable || $field->nullable) as $child) {
                    $flat[] = $child;
                }
                continue;
            }
            // Timestamps are nullable in PHP so new entities can omit them, but the ORM always
            // writes them, so their columns are NOT NULL.
            $flat[] = [$field, $parentNullable || ($field->nullable || $field->generated) && !$field->createdAt && !$field->updatedAt && !$field->id];
        }

        return $flat;
    }

    private static function column(Field $field, bool $nullable): string
    {
        $name = var_export($field->column, true);
        $type = $field->kind === 'wrapper' ? $field->innerType ?? 'string' : $field->type;
        $call = match (true) {
            $field->kind === 'json' => sprintf('json(%s)', $name),
            $field->kind === 'custom' => sprintf(
                'text(%s) /* TODO: check the type for %s */',
                $name,
                $field->converter === null ? 'its ColumnType' : $field->converter::class,
            ),
            $type === 'int' => sprintf('bigInteger(%s)', $name),
            $type === 'float' => sprintf('float(%s)', $name),
            $type === 'bool' => sprintf('boolean(%s)', $name),
            $type === DateTimeImmutable::class => sprintf('instant(%s)', $name),
            $type === LocalDate::class => sprintf('date(%s)', $name),
            enum_exists($type) && is_subclass_of($type, BackedEnum::class) && (string) new ReflectionEnum($type)->getBackingType() === 'int' => sprintf(
                'integer(%s)',
                $name,
            ),
            enum_exists($type) => sprintf('string(%s, 50)', $name),
            default => sprintf('string(%s)', $name),
        };
        $modifiers = '';
        if ($nullable) {
            $modifiers .= '->nullable()';
        }
        $default = $field->default instanceof BackedEnum ? $field->default->value : $field->default;
        if ($field->hasDefault && $default !== null && is_scalar($default) && $field->kind !== 'json') {
            $modifiers .= sprintf('->default(%s)', var_export($default, true));
        }
        return '$table->' . $call . $modifiers . ';';
    }

    /**
     * @param 'create'|'alter' $method
     * @param list<string> $lines
     */
    private static function block(string $method, string $table, array $lines): string
    {
        return sprintf(
            "        \$schema->%s(%s, static function (Blueprint \$table): void {\n%s\n        });",
            $method,
            var_export($table, true),
            implode("\n", array_map(static fn (string $line): string => '            ' . $line, $lines)),
        );
    }
}

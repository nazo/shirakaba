<?php

declare(strict_types=1);

namespace Shirakaba\Orm\Tests;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Shirakaba\Database\Database;
use Shirakaba\Database\Testing\TestDatabases;
use Shirakaba\Database\Writer;
use Shirakaba\Orm\Entities;
use Shirakaba\Orm\EntityQuery;
use Shirakaba\Orm\NotDeleted;
use Shirakaba\Orm\Scope;
use Shirakaba\Orm\ScopeMissing;
use Shirakaba\Orm\ScopeViolation;
use Shirakaba\Orm\Tests\Fixtures\InTeam;
use Shirakaba\Orm\Tests\Fixtures\Issue;
use Shirakaba\Orm\Tests\Fixtures\Project;
use Shirakaba\Orm\Tests\Fixtures\ProjectView;

#[CoversClass(EntityQuery::class)]
#[CoversClass(NotDeleted::class)]
#[CoversClass(ScopeMissing::class)]
final class ScopeTest extends TestCase
{
    /**
     * @return array<string, array{Database}>
     */
    public static function databases(): array
    {
        return TestDatabases::available();
    }

    private static function schema(Database $database): Writer
    {
        $db = $database->connect()->writer();
        $db->execute('DROP TABLE IF EXISTS orm_issues');
        $db->execute('DROP TABLE IF EXISTS orm_projects');
        [$id, $instant] = match ($db->dialect()->name()) {
            'mysql' => ['BIGINT AUTO_INCREMENT PRIMARY KEY', 'DATETIME(6)'],
            'pgsql' => ['BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'TIMESTAMPTZ(6)'],
            default => ['INTEGER PRIMARY KEY AUTOINCREMENT', 'TEXT'],
        };
        $db->execute("CREATE TABLE orm_projects (id $id, team INT NOT NULL, name VARCHAR(50) NOT NULL, deleted_at $instant NULL)");
        $db->execute("CREATE TABLE orm_issues (id $id, team INT NOT NULL, project_id BIGINT NOT NULL, title VARCHAR(50) NOT NULL, deleted_at $instant NULL)");

        return $db;
    }

    /**
     * @param list<Project> $projects
     * @return list<string>
     */
    private static function names(array $projects): array
    {
        return array_map(static fn (Project $project): string => $project->name, $projects);
    }

    /**
     * No scopes, typed loosely enough that PHPStan's required-scope rule leaves the
     * call to ScopeMissing, which these tests check.
     *
     * @return list<Scope>
     */
    private static function forgotten(): array
    {
        return [];
    }

    #[DataProvider('databases')]
    public function testRequiredAndSoftDeleteScopes(Database $database): void
    {
        $db = self::schema($database);
        $mine = Entities::insert(new Project(1, 'Mine'), $db, scopes: [new InTeam(1)]);
        $theirs = Entities::insert(new Project(2, 'Theirs'), $db, scopes: [new InTeam(2)]);
        $gone = Entities::insert(new Project(1, 'Gone'), $db, scopes: [new InTeam(1)]);
        Entities::insertAll(
            [
                new Issue(1, $mine->id ?? 0, 'Open'),
                new Issue(1, $mine->id ?? 0, 'Closed'),
            ],
            $db,
            scopes: [new InTeam(1)],
        );
        Entities::insertAll([new Issue(2, $theirs->id ?? 0, 'Elsewhere')], $db, scopes: [new InTeam(2)]);
        $team = new InTeam(1);
        Entities::delete($gone, $db, scopes: [$team]);
        $closed = Entities::query(Issue::class)->scoped($team)->where('title', '=', 'Closed')->first($db);
        self::assertNotNull($closed);
        Entities::delete($closed, $db, scopes: [$team]);

        self::assertSame(['Mine'], self::names(Entities::query(Project::class)->scoped($team)->orderBy('id')->fetch($db)));
        self::assertSame(
            ['Mine', 'Gone'],
            self::names(Entities::query(Project::class)->scoped($team)->withoutScope(NotDeleted::class)->orderBy('id')->fetch($db)),
        );
        self::assertSame(['Mine', 'Theirs'], self::names(Entities::query(Project::class)->withoutScope(InTeam::class)->orderBy('id')->fetch($db)));
        self::assertNull(Entities::find(Project::class, $theirs->id, $db, [$team]), 'Another team\'s project is invisible.');

        $views = Entities::query(Project::class)->scoped($team)->with('issues')->into(ProjectView::class, $db);
        self::assertSame(
            ['Open'],
            array_map(static fn (Issue $issue): string => $issue->title, ($views[0] ?? null)->issues ?? []),
            'Related entities get the scopes too.',
        );
        self::assertSame(1, Entities::query(Project::class)->scoped($team)->whereHas('issues')->count($db));

        self::assertSame(1, Entities::query(Issue::class)->scoped($team)->delete($db), 'A bulk delete is soft and stays in the team.');
        self::assertSame(0, Entities::query(Issue::class)->scoped($team)->count($db));
        self::assertSame(1, Entities::query(Issue::class)->withoutScope(InTeam::class)->count($db), 'The other team keeps its issue.');

        self::assertTrue(Entities::restore($gone, $db, scopes: [$team]));
        self::assertSame(2, Entities::query(Project::class)->scoped($team)->count($db));
        self::assertTrue(Entities::forceDelete($gone, $db, scopes: [$team]));
        self::assertSame(2, Entities::query(Project::class)->withoutScope(InTeam::class, NotDeleted::class)->count($db));
    }

    #[DataProvider('databases')]
    public function testWritesByKeyStayInsideTheScope(Database $database): void
    {
        $db = self::schema($database);
        $theirs = Entities::insert(new Project(2, 'Theirs'), $db, scopes: [new InTeam(2)]);
        $mine = new InTeam(1);
        $forged = new Project(1, 'Hijacked', id: $theirs->id);

        self::assertSame(0, Entities::patch(Project::class, $theirs->id, ['name' => 'Hijacked'], $db, scopes: [$mine]));
        Entities::update($forged, $db, scopes: [$mine]);
        self::assertFalse(Entities::delete($theirs, $db, scopes: [$mine]));
        self::assertFalse(Entities::forceDelete($theirs, $db, scopes: [$mine]));

        $stored = Entities::get(Project::class, $theirs->id, $db, [new InTeam(2)]);
        self::assertSame('Theirs', $stored->name, 'A forged key in another team changed nothing.');
        self::assertNull($stored->deletedAt);

        $this->expectException(ScopeMissing::class);
        Entities::patch(Project::class, $theirs->id, ['name' => 'Hijacked'], $db, scopes: self::forgotten());
    }

    public function testInsertsNeedTheScopeAndStayInsideIt(): void
    {
        $db = self::schema(new Database(static fn (): \PDO => new \PDO('sqlite::memory:')));
        try {
            Entities::insert(new Project(1, 'No scope'), $db, scopes: self::forgotten());
            self::fail('An insert without the required scope must fail.');
        } catch (ScopeMissing $e) {
            self::assertStringContainsString('Inserting ' . Project::class . ' needs its scope', $e->getMessage());
        }
        try {
            Entities::insertAll([new Project(1, 'Mine'), new Project(2, 'Forged')], $db, scopes: [new InTeam(1)]);
            self::fail('An entity of another team must be refused.');
        } catch (ScopeViolation $e) {
            self::assertStringContainsString(InTeam::class, $e->getMessage());
        }

        self::assertSame(0, Entities::query(Project::class)->withoutScope(InTeam::class, NotDeleted::class)->count($db), 'Nothing was inserted.');
    }

    public function testLoadTakesTheRelatedEntitysScopes(): void
    {
        $db = self::schema(new Database(static fn (): \PDO => new \PDO('sqlite::memory:')));
        $project = Entities::insert(new Project(1, 'Mine'), $db, scopes: [new InTeam(1)]);
        Entities::insertAll([new Issue(1, $project->id ?? 0, 'Open')], $db, scopes: [new InTeam(1)]);
        Entities::insertAll([new Issue(2, $project->id ?? 0, 'Leaked')], $db, scopes: [new InTeam(2)]);

        $issues = Entities::load([$project], 'issues', $db, [new InTeam(1)])[0] ?? [];
        self::assertIsArray($issues);
        self::assertSame(
            ['Open'],
            array_map(static fn (mixed $issue): string => $issue instanceof Issue ? $issue->title : '?', $issues),
            'The other team\'s issue stays out.',
        );

        $this->expectException(ScopeMissing::class);
        Entities::load([$project], 'issues', $db, self::forgotten());
    }

    public function testUpsertRefusesEntitiesWithRequiredScopes(): void
    {
        $db = self::schema(new Database(static fn (): \PDO => new \PDO('sqlite::memory:')));

        $this->expectException(\LogicException::class);
        $this->expectExceptionMessage('cannot keep');
        Entities::upsert(new Project(1, 'x'), ['name'], $db);
    }

    public function testRequiredScopesCannotBeForgotten(): void
    {
        $db = self::schema(new Database(static fn (): \PDO => new \PDO('sqlite::memory:')));

        $this->expectException(ScopeMissing::class);
        $this->expectExceptionMessage('need ->scoped(new Shirakaba\Orm\Tests\Fixtures\InTeam(...))');
        $query = Entities::query(Project::class);
        $query->fetch($db);
    }
}

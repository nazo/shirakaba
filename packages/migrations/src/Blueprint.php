<?php

declare(strict_types=1);

namespace Shirakaba\Migrations;

/**
 * The columns, keys and indexes of a table being created or altered.
 *
 * Types follow design/07-date-and-time.md: instant() is TIMESTAMPTZ(6) on PostgreSQL,
 * DATETIME(6) holding UTC on MySQL and text on SQLite; date() is DATE, or text on SQLite.
 */
final class Blueprint
{
    /** @var list<Column> */
    private array $columns = [];

    /** @var list<string> */
    private array $primary = [];

    /** @var list<Index> */
    private array $indexes = [];

    /** @var list<ForeignKey> */
    private array $foreignKeys = [];

    /** @var list<string> */
    private array $dropColumns = [];

    /** @var list<array{string, string}> */
    private array $renameColumns = [];

    /** @var list<string> */
    private array $dropIndexes = [];

    public function __construct(
        public readonly string $table,
    ) {}

    /**
     * An auto-incrementing BIGINT primary key.
     */
    public function id(string $name = 'id'): Column
    {
        return $this->add(
            new Column(
                $name,
                [
                    'mysql' => 'BIGINT AUTO_INCREMENT PRIMARY KEY',
                    'pgsql' => 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                    'sqlite' => 'INTEGER PRIMARY KEY AUTOINCREMENT',
                ],
                primaryKey: true,
            ),
        );
    }

    public function integer(string $name): Column
    {
        return $this->add(new Column($name, self::same('INTEGER', mysql: 'INT')));
    }

    public function bigInteger(string $name): Column
    {
        return $this->add(new Column($name, self::same('BIGINT', sqlite: 'INTEGER')));
    }

    /**
     * @param positive-int $length
     */
    public function string(string $name, int $length = 255): Column
    {
        return $this->add(new Column($name, self::same(sprintf('VARCHAR(%d)', $length))));
    }

    public function text(string $name): Column
    {
        return $this->add(new Column($name, self::same('TEXT', mysql: 'LONGTEXT')));
    }

    public function boolean(string $name): Column
    {
        return $this->add(new Column($name, self::same('BOOLEAN')));
    }

    /**
     * @param positive-int $precision
     * @param int<0, max> $scale
     */
    public function decimal(string $name, int $precision = 10, int $scale = 2): Column
    {
        return $this->add(new Column($name, self::same(sprintf('DECIMAL(%d, %d)', $precision, $scale))));
    }

    public function float(string $name): Column
    {
        return $this->add(new Column($name, self::same('DOUBLE PRECISION', mysql: 'DOUBLE', sqlite: 'REAL')));
    }

    /**
     * A point in time, stored in UTC with microseconds.
     */
    public function instant(string $name): Column
    {
        return $this->add(new Column($name, self::same('TIMESTAMPTZ(6)', mysql: 'DATETIME(6)', sqlite: 'TEXT')));
    }

    /**
     * A calendar date (LocalDate).
     */
    public function date(string $name): Column
    {
        return $this->add(new Column($name, self::same('DATE', sqlite: 'TEXT')));
    }

    public function json(string $name): Column
    {
        return $this->add(new Column($name, self::same('JSONB', mysql: 'JSON', sqlite: 'TEXT')));
    }

    public function binary(string $name): Column
    {
        return $this->add(new Column($name, self::same('BYTEA', mysql: 'LONGBLOB', sqlite: 'BLOB')));
    }

    public function uuid(string $name): Column
    {
        return $this->add(new Column($name, self::same('UUID', mysql: 'CHAR(36)', sqlite: 'TEXT')));
    }

    /**
     * A column with a type given per dialect, for anything the methods above do not cover.
     *
     * @param array{mysql: string, pgsql: string, sqlite: string} $types
     */
    public function custom(string $name, array $types): Column
    {
        return $this->add(new Column($name, $types));
    }

    /**
     * A composite primary key.
     *
     * @param non-empty-list<string> $columns
     */
    public function primary(array $columns): void
    {
        $this->primary = $columns;
    }

    /**
     * @param non-empty-list<string> $columns
     */
    public function index(array $columns, ?string $name = null): Index
    {
        return $this->indexes[] = new Index($name ?? $this->table . '_' . implode('_', $columns) . '_index', false, $columns);
    }

    /**
     * @param non-empty-list<string> $columns
     */
    public function unique(array $columns, ?string $name = null): Index
    {
        return $this->indexes[] = new Index($name ?? $this->table . '_' . implode('_', $columns) . '_unique', true, $columns);
    }

    /**
     * An index on an SQL expression, such as `lower(email)`; queries must use the
     * same expression to use it. The expression is written into the statement as given.
     */
    public function expressionIndex(string $name, string $expression, bool $unique = false): Index
    {
        return $this->indexes[] = new Index($name, $unique, [], $expression);
    }

    public function foreign(string $column, ?string $name = null): ForeignKey
    {
        $key = new ForeignKey($column, $name ?? $this->table . '_' . $column . '_foreign');
        $this->foreignKeys[] = $key;

        return $key;
    }

    public function dropColumn(string $name): void
    {
        $this->dropColumns[] = $name;
    }

    public function renameColumn(string $from, string $to): void
    {
        $this->renameColumns[] = [$from, $to];
    }

    public function dropIndex(string $name): void
    {
        $this->dropIndexes[] = $name;
    }

    /**
     * What an alter changes, for linting.
     *
     * @internal
     * @return list<Operation>
     */
    public function alterOperations(): array
    {
        $operations = [];
        foreach ($this->dropColumns as $column) {
            $operations[] = new Operation('dropColumn', $this->table, $column);
        }
        foreach ($this->renameColumns as [$from, $to]) {
            $operations[] = new Operation('renameColumn', $this->table, $from . ' -> ' . $to);
        }
        foreach ($this->columns as $column) {
            $operations[] = new Operation($column->isNullable() || $column->hasDefault() ? 'addColumn' : 'addRequiredColumn', $this->table, $column->name);
        }
        foreach ($this->dropIndexes as $index) {
            $operations[] = new Operation('dropIndex', $this->table, $index);
        }
        foreach ($this->indexes as $index) {
            $operations[] = new Operation($index->unique ? 'addUniqueIndex' : 'addIndex', $this->table, $index->name);
        }
        foreach ($this->columns as $column) {
            if ($column->isUnique()) {
                $operations[] = new Operation('addUniqueIndex', $this->table, $this->table . '_' . $column->name . '_unique');
            }
        }
        foreach ($this->foreignKeys as $key) {
            $operations[] = new Operation('addForeignKey', $this->table, $key->name);
        }

        return $operations;
    }

    /**
     * @internal
     * @return list<string>
     */
    public function createStatements(\Shirakaba\Database\Dialect\Dialect $dialect): array
    {
        if ($this->columns === []) {
            throw new \LogicException(sprintf('Table "%s" has no columns.', $this->table));
        }
        $parts = array_map(static fn (Column $column): string => $column->definition($dialect), $this->columns);
        if ($this->primary !== []) {
            $parts[] = 'PRIMARY KEY (' . implode(', ', array_map($dialect->quoteIdentifier(...), $this->primary)) . ')';
        }
        foreach ($this->foreignKeys as $key) {
            $parts[] = $key->definition($dialect);
        }
        $sql = sprintf("CREATE TABLE %s (\n    %s\n)", $dialect->quoteIdentifier($this->table), implode(",\n    ", $parts));
        if ($dialect->name() === 'mysql') {
            $sql .= ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci';
        }

        return [$sql, ...$this->indexStatements($dialect)];
    }

    /**
     * @internal
     * @return list<string>
     */
    public function alterStatements(\Shirakaba\Database\Dialect\Dialect $dialect): array
    {
        $table = $dialect->quoteIdentifier($this->table);
        $statements = [];
        foreach ($this->dropIndexes as $index) {
            $statements[] = $dialect->name() === 'mysql'
                ? sprintf('DROP INDEX %s ON %s', $dialect->quoteIdentifier($index), $table)
                : 'DROP INDEX ' . $dialect->quoteIdentifier($index);
        }
        foreach ($this->renameColumns as [$from, $to]) {
            $statements[] = sprintf('ALTER TABLE %s RENAME COLUMN %s TO %s', $table, $dialect->quoteIdentifier($from), $dialect->quoteIdentifier($to));
        }
        foreach ($this->dropColumns as $column) {
            $statements[] = sprintf('ALTER TABLE %s DROP COLUMN %s', $table, $dialect->quoteIdentifier($column));
        }
        foreach ($this->columns as $column) {
            $statements[] = sprintf('ALTER TABLE %s ADD COLUMN %s', $table, $column->definition($dialect));
        }
        if ($this->primary !== []) {
            throw new \LogicException('A primary key cannot be added to an existing table here; create the table with it.');
        }
        foreach ($this->foreignKeys as $key) {
            if ($dialect->name() === 'sqlite') {
                throw new \LogicException('SQLite cannot add a foreign key to an existing table; recreate the table.');
            }
            $statements[] = sprintf('ALTER TABLE %s ADD %s', $table, $key->definition($dialect));
        }

        return [...$statements, ...$this->indexStatements($dialect)];
    }

    /**
     * @return list<string>
     */
    private function indexStatements(\Shirakaba\Database\Dialect\Dialect $dialect): array
    {
        $statements = [];
        $indexes = $this->indexes;
        foreach ($this->columns as $column) {
            if ($column->isUnique()) {
                $indexes[] = new Index($this->table . '_' . $column->name . '_unique', true, [$column->name]);
            }
        }
        foreach ($indexes as $index) {
            $statements = [...$statements, ...$index->statements($dialect, $this->table)];
        }

        return $statements;
    }

    private function add(Column $column): Column
    {
        $this->columns[] = $column;

        return $column;
    }

    /**
     * @return array{mysql: string, pgsql: string, sqlite: string}
     */
    private static function same(string $type, ?string $mysql = null, ?string $sqlite = null): array
    {
        return ['mysql' => $mysql ?? $type, 'pgsql' => $type, 'sqlite' => $sqlite ?? $type];
    }
}

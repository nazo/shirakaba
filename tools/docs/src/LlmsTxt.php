<?php

declare(strict_types=1);

namespace Shirakaba\Tools\Docs;

/**
 * Builds llms.txt (an index with one line per document) and llms-full.txt (every document
 * in full) from shirakaba/docs (design/13-static-analysis-and-agents.md), following https://llmstxt.org. Only the
 * documents that ship in the package are included: the agent index, the guide, the design documents, the
 * error pages and the API index; links are relative to the package.
 */
final readonly class LlmsTxt
{
    private const string SUMMARY = 'Shirakaba is a PHP 8.5 web framework: a small, PSR-compliant core with official packages for JSON APIs, databases and an ORM, authentication, OpenAPI, background jobs and real-time events, configured in PHP and checked by PHPStan at level max. It is not in model training data; read these documents instead of assuming another framework\'s API.';

    public static function index(string $docs): string
    {
        $lines = [
            '# Shirakaba',
            '',
            '> ' . self::SUMMARY,
            '',
            'Generated by `composer docs:generate`; do not edit.',
            '',
            '## Start here',
            '',
            self::entry($docs, 'index.md'),
            '- [API index](api.md): every public class, interface and enum of every package, with a one-line summary and its file.',
            '',
            '## Guide',
            '',
        ];
        foreach (self::files($docs, 'guide') as $file) {
            $lines[] = self::entry($docs, $file, sections: true);
        }
        $lines = [...$lines, '', '## Design', ''];
        foreach (self::files($docs, 'design') as $file) {
            $lines[] = self::entry($docs, $file);
        }
        $lines = [...$lines, '', '## Error pages', ''];
        foreach (self::files($docs, 'messages') as $file) {
            $lines[] = self::entry($docs, $file);
        }
        $lines = [...$lines, '', '## Problem codes sent to clients', ''];
        foreach (self::files($docs, 'problems') as $file) {
            $lines[] = self::entry($docs, $file);
        }

        return implode("\n", $lines) . "\n";
    }

    public static function full(string $docs): string
    {
        $parts = ['# Shirakaba', '', '> ' . self::SUMMARY, '', 'Generated by `composer docs:generate`; do not edit. Every document of shirakaba/docs in full.'];
        foreach (['index.md', ...self::files($docs, 'guide'), ...self::files($docs, 'design'), ...self::files($docs, 'messages'), ...self::files($docs, 'problems'), 'api.md'] as $file) {
            $parts[] = '';
            $parts[] = '---';
            $parts[] = '';
            $parts[] = sprintf('<!-- %s -->', $file);
            $parts[] = '';
            $parts[] = rtrim(self::read($docs . '/' . $file));
        }

        return implode("\n", $parts) . "\n";
    }

    /**
     * The chapters or records of a directory in order, without its README.
     *
     * @return list<string> paths relative to $docs
     */
    private static function files(string $docs, string $directory): array
    {
        $files = glob($docs . '/' . $directory . '/*.md');
        $files = array_values(array_filter($files === false ? [] : $files, static fn (string $file): bool => basename($file) !== 'README.md'));
        sort($files);

        return array_map(static fn (string $file): string => $directory . '/' . basename($file), $files);
    }

    /**
     * One index line: the title and the first sentence, or for guide chapters, which are
     * mostly examples, the sections they cover.
     */
    private static function entry(string $docs, string $file, bool $sections = false): string
    {
        $text = self::read($docs . '/' . $file);
        $title = preg_match('/^# (.+)$/m', $text, $match) === 1 ? trim($match[1]) : $file;
        $summary = self::summary($text);
        $code = (string) preg_replace('/^```.*?^```/ms', '', $text);
        if ($sections && preg_match_all('/^## (.+)$/m', $code, $headings) > 0) {
            $summary = 'covers ' . implode(', ', array_map(trim(...), $headings[1])) . '.';
        }

        return sprintf('- [%s](%s)%s', self::escape($title), $file, $summary === '' ? '' : ': ' . $summary);
    }

    /**
     * The first sentence of the first paragraph of prose: after the title, skipping metadata
     * lists, headings and code.
     */
    private static function summary(string $text): string
    {
        $paragraphs = preg_split('/\n\s*\n/', (string) preg_replace('/^```.*?^```/ms', '', $text));
        foreach ($paragraphs === false ? [] : $paragraphs as $paragraph) {
            $paragraph = trim($paragraph);
            if ($paragraph === '' || preg_match('/^(#|-|\||```|>|\d+\.)/', $paragraph) === 1) {
                continue;
            }
            $flat = (string) preg_replace('/\s+/', ' ', $paragraph);
            $sentence = preg_match('/^(.+?[.!?])(\s|$)/', $flat, $match) === 1 ? $match[1] : $flat;

            return self::escape((string) preg_replace('/\[([^\]]+)\]\([^)]+\)/', '$1', $sentence));
        }

        return '';
    }

    /**
     * Brackets in titles and summaries (such as #[Db]) would end the link text; inside code
     * spans they are literal already.
     */
    private static function escape(string $text): string
    {
        $parts = explode('`', $text);
        foreach ($parts as $index => $part) {
            if ($index % 2 === 0) {
                $parts[$index] = str_replace(['[', ']'], ['\\[', '\\]'], $part);
            }
        }

        return implode('`', $parts);
    }

    private static function read(string $file): string
    {
        $text = file_get_contents($file);

        return $text === false ? '' : $text;
    }
}
